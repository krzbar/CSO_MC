## =====================================================================
##  Basins of attraction of a discrete dynamical system on the
##  4-dimensional unit simplex, visualised as a grid of ternary slices.
##
##  Base R only (graphics via plot / rasterImage).
##
##  The map V must be VECTORISED:  it takes an (m x 4) matrix X whose
##  rows are points of the simplex and returns an (m x 4) matrix V(X).
##
##  Sections:  1. basins_simplex4()  compute basins on slices
##             2. plot.basins4()     draw the grid of ternary panels
##             3. basins_figure()    compute + plot to PDF in one call
##             4. basins_batch()     figures for a list of systems
## =====================================================================

## ---------------------------------------------------------------------
## 1. Compute the basins
## ---------------------------------------------------------------------
##  V            : vectorised map, matrix (m x 4) -> matrix (m x 4)
##  slice_values : values c at which the coordinate x[slice_coord] is fixed
##                 (0 <= c < 1; at c = 1 the slice is a single point)
##  slice_coord  : which of the four coordinates is fixed (default 4)
##  n_pix        : pixel resolution (width of each triangle in pixels)
##  max_iter     : iteration cap
##  tol          : convergence tolerance (max |x_{t+1}-x_t| per point)
##  cluster_tol  : limit points closer than this are the same attractor
##  renormalise  : rescale each iterate to sum 1 (removes rounding drift)
##  verbose      : print progress
basins_simplex4 <- function(V, slice_values = c(0, 0.2, 0.3, 0.4),
                            slice_coord = 4, n_pix = 300,
                            max_iter = 2000, tol = 1e-9,
                            cluster_tol = 1e-3, renormalise = TRUE,
                            verbose = TRUE) {
  stopifnot(slice_coord %in% 1:4, all(slice_values >= 0 & slice_values < 1))
  free  <- setdiff(1:4, slice_coord)          # the three free coordinates
  h     <- sqrt(3) / 2                        # height of unit triangle
  n_u   <- n_pix
  n_v   <- max(2L, round(n_pix * h))
  ## pixel centres in Cartesian coordinates of the unit triangle
  u <- (seq_len(n_u) - 0.5) / n_u
  v <- (seq_len(n_v) - 0.5) / n_v * h
  grid <- expand.grid(u = u, v = v)
  ## Cartesian -> barycentric (a,b,c): vertex a=(0,0), b=(1,0), c=(1/2,h)
  cc <- grid$v / h
  bb <- grid$u - cc / 2
  aa <- 1 - bb - cc
  inside <- aa >= 0 & bb >= 0 & cc >= 0
  bary <- cbind(aa, bb, cc)[inside, , drop = FALSE]
  m <- nrow(bary)

  slices <- vector("list", length(slice_values))
  all_limits <- NULL
  for (s in seq_along(slice_values)) {
    cval <- slice_values[s]
    if (verbose) cat(sprintf("slice %d/%d: x%d = %g (%d points) ... ",
                             s, length(slice_values), slice_coord, cval, m))
    X <- matrix(0, m, 4)
    X[, free]        <- bary * (1 - cval)
    X[, slice_coord] <- cval
    iters  <- rep(NA_integer_, m)
    active <- rep(TRUE, m)
    for (it in seq_len(max_iter)) {
      idx  <- which(active)
      if (length(idx) == 0) break
      Xn <- V(X[idx, , drop = FALSE])
      if (renormalise) Xn <- Xn / rowSums(Xn)
      d  <- apply(abs(Xn - X[idx, , drop = FALSE]), 1, max)
      X[idx, ] <- Xn
      done <- d < tol
      iters[idx[done]]  <- it
      active[idx[done]] <- FALSE
    }
    if (verbose) cat(sprintf("%d not converged\n", sum(active)))
    slices[[s]] <- list(c = cval, limit = X, iters = iters,
                        converged = !active)
    all_limits <- rbind(all_limits, X[!active, , drop = FALSE])
  }

  ## ---- cluster the limit points into attractors (greedy, no analysis)
  key <- unique(round(all_limits, -log10(cluster_tol)))
  attractors <- NULL
  for (i in seq_len(nrow(key))) {
    p <- key[i, ]
    if (is.null(attractors) ||
        min(sqrt(rowSums((attractors - rep(p, each = nrow(attractors)))^2))) > cluster_tol)
      attractors <- rbind(attractors, p)
  }
  rownames(attractors) <- NULL
  colnames(attractors) <- paste0("x", 1:4)
  ## order attractors lexicographically for reproducible colours
  attractors <- attractors[do.call(order, as.data.frame(-attractors)), , drop = FALSE]
  K <- nrow(attractors)

  nearest <- function(P) {           # index of nearest attractor per row
    D <- sapply(seq_len(K), function(k)
      sqrt(rowSums((P - rep(attractors[k, ], each = nrow(P)))^2)))
    D <- matrix(D, nrow = nrow(P))
    max.col(-D, ties.method = "first")
  }
  ## ---- build label / iteration images for each slice
  for (s in seq_along(slices)) {
    lab <- rep(NA_integer_, nrow(grid))        # NA = outside triangle
    itr <- rep(NA_integer_, nrow(grid))
    lab_in <- rep(0L, m)                       # 0 = not converged
    if (any(slices[[s]]$converged))
      lab_in[slices[[s]]$converged] <-
        nearest(slices[[s]]$limit[slices[[s]]$converged, , drop = FALSE])
    lab[inside] <- lab_in
    itr[inside] <- slices[[s]]$iters
    ## matrices with rows = v (bottom row first), columns = u
    slices[[s]]$label <- matrix(lab, n_v, n_u, byrow = TRUE)
    slices[[s]]$iters_img <- matrix(itr, n_v, n_u, byrow = TRUE)
    slices[[s]]$fraction <- c(table(factor(lab_in, levels = 0:K))) / m
    slices[[s]]$limit <- NULL                  # drop bulky data
  }
  structure(list(slices = slices, attractors = attractors,
                 slice_coord = slice_coord, free = free,
                 slice_values = slice_values, max_iter = max_iter),
            class = "basins4")
}

## ---------------------------------------------------------------------
## 2. Plot the basins (base graphics)
## ---------------------------------------------------------------------
##  b             : result of basins_simplex4()
##  The panels form a square-ish grid determined by the number of slices
##  (4 -> 2 x 2, 9 -> 3 x 3, 6 -> 2 x 3, ...).
##  The legend is written with text() / rect() AFTER all slices are
##  drawn, into the upper-left corner of the top-right panel (the white
##  gap between that triangle and the one to its left).
##  legend_xy     : c(x, y) position of the legend's top-left corner in
##                  device coordinates (0..1); NULL = automatic
##  cols          : one colour per attractor (default: light qualitative set)
##  col_nonconv   : colour of points that did not converge
##  shade_by_time : darken pixels (log scale) by convergence time
##  shade_strength: 0 = no darkening, 1 = darkest pixels become black
##  true_scale    : draw slice x=c at its true size (1-c) instead of unit size
##  cex_main, cex_lab, cex_legend : font sizes (titles, vertex labels, legend)
plot.basins4 <- function(b, cols = NULL,
                         col_nonconv = "black", shade_by_time = TRUE,
                         shade_strength = 0.35, true_scale = FALSE,
                         vertex_labels = TRUE, legend_xy = NULL,
                         cex_main = 2.6, cex_lab = 2.4, cex_legend = 2.0,
                         legend_title = "attractors", ...) {
  K <- nrow(b$attractors)
  S <- length(b$slices)
  if (is.null(cols)) {
    base_cols <- c("#E6194B", "#3CB44B", "#4363D8", "#F58231", "#911EB4",
                   "#42D4F4", "#F032E6", "#BFEF45", "#FABED4", "#469990",
                   "#DCBEFF", "#9A6324", "#FFFAC8", "#800000", "#AAFFC3")
    ## lighten: mix 35% white into each colour
    base_cols <- apply(col2rgb(base_cols) / 255, 2, function(v)
      rgb(0.65 * v[1] + 0.35, 0.65 * v[2] + 0.35, 0.65 * v[3] + 0.35))
    cols <- rep(base_cols, length.out = K)
  }
  stopifnot(length(cols) == K)
  h <- sqrt(3) / 2

  ## ---- square-ish grid of slices (2x2 for 4 slices, 3x3 for 9, ...)
  nc <- ceiling(sqrt(S)); nr <- ceiling(S / nc)
  op <- par(mfrow = c(nr, nc), mar = c(1.8, 0.3, 4.2, 0.3), xpd = NA)
  on.exit(par(op))

  tmax <- max(unlist(lapply(b$slices, function(s) s$iters_img)), na.rm = TRUE)
  for (s in seq_len(S)) {
    sl  <- b$slices[[s]]
    lab <- sl$label
    img <- matrix(NA_character_, nrow(lab), ncol(lab))
    for (k in seq_len(K)) {
      sel <- which(lab == k)
      if (length(sel) == 0) next
      if (shade_by_time) {
        f    <- log1p(sl$iters_img[sel]) / log1p(tmax)   # log scale in [0,1]
        rgbk <- col2rgb(cols[k]) / 255
        img[sel] <- rgb(rgbk[1] * (1 - shade_strength * f),
                        rgbk[2] * (1 - shade_strength * f),
                        rgbk[3] * (1 - shade_strength * f))
      } else img[sel] <- cols[k]
    }
    img[which(lab == 0)] <- col_nonconv
    img[is.na(lab)] <- NA                               # transparent outside
    ras <- as.raster(img[nrow(img):1, , drop = FALSE])  # top row first
    sc <- if (true_scale) 1 - sl$c else 1
    plot.new()
    plot.window(xlim = c(-0.06, 1.06), ylim = c(-0.10, h + 0.04), asp = 1)
    rasterImage(ras, 0, 0, sc, sc * h, interpolate = FALSE)
    polygon(c(0, sc, sc / 2), c(0, 0, sc * h), border = "grey30", lwd = 1)
    title(main = bquote(x[.(b$slice_coord)] == .(sl$c)), line = 2.2,
          cex.main = cex_main, font.main = 1)
    if (vertex_labels) {
      text(0, 0,           bquote(x[.(b$free[1])]), pos = 1, cex = cex_lab, offset = 0.6)
      text(sc, 0,          bquote(x[.(b$free[2])]), pos = 1, cex = cex_lab, offset = 0.6)
      text(sc / 2, sc * h, bquote(x[.(b$free[3])]), pos = 3, cex = cex_lab, offset = 0.5)
    }
  }

  ## ---- legend written as text into the white space
  labs <- apply(b$attractors, 1, function(p)
    paste0("(", paste(format(round(p, 3)), collapse = ","), ")"))
  nc_flag <- any(sapply(b$slices, function(s) any(s$label == 0, na.rm = TRUE)))
  if (nc_flag) { labs <- c(labs, "not converged"); cols <- c(cols, col_nonconv) }
  par(fig = c(0, 1, 0, 1), mar = c(0, 0, 0, 0), new = TRUE, xpd = NA)
  plot.new(); plot.window(c(0, 1), c(0, 1))
  lh  <- 1.45 * strheight("X", cex = cex_legend)      # line height
  bw  <- 0.8 * strheight("X", cex = cex_legend)       # colour box side
  ## default: upper-left corner of the top-right panel, i.e. in the gap
  ## between the apex of that panel's triangle and its left neighbour
  if (is.null(legend_xy)) legend_xy <- c((nc - 1) / nc + 0.004, 1 - 0.02 / nr)
  x0 <- legend_xy[1]; y <- legend_xy[2]
  if (!is.null(legend_title) && nzchar(legend_title)) {
    text(x0, y, legend_title, adj = c(0, 1), cex = cex_legend, font = 1)
    y <- y - lh
  }
  for (k in seq_along(labs)) {
    rect(x0, y - bw, x0 + bw, y, col = cols[k], border = NA)
    text(x0 + 1.5 * bw, y - bw / 2, labs[k], adj = c(0, 0.5), cex = cex_legend)
    y <- y - lh
  }
  invisible(NULL)
}

## ---------------------------------------------------------------------
## 3. One-call wrapper: compute + plot to PDF (and optionally PNG)
## ---------------------------------------------------------------------
##  V            : vectorised map, matrix (m x 4) -> matrix (m x 4)
##  slice_values : the values at which coordinate x[slice_coord] is fixed;
##                 one panel per value (4 values -> 2x2 grid, 9 -> 3x3)
##  slice_coord  : which coordinate is sliced (1..4)
##  file         : output PDF file name (NULL = draw on current device)
##  width,height : PDF size in inches (NULL = chosen from the grid size)
##  png          : also write a PNG with the same base name
##  ...          : further arguments passed to basins_simplex4() (n_pix,
##                 max_iter, tol, ...) or to plot.basins4() (cols,
##                 shade_strength, legend_xy, cex_*, ...)
basins_figure <- function(V, slice_values, slice_coord = 4, file = NULL,
                          width = NULL, height = NULL, png = FALSE,
                          n_pix = 400, ...) {
  dots <- list(...)
  comp_args <- intersect(names(dots), names(formals(basins_simplex4)))
  plot_args <- setdiff(names(dots), comp_args)
  b <- do.call(basins_simplex4,
               c(list(V = V, slice_values = slice_values,
                      slice_coord = slice_coord, n_pix = n_pix), dots[comp_args]))
  S  <- length(slice_values)
  nc <- ceiling(sqrt(S)); nr <- ceiling(S / nc)
  if (is.null(width))  width  <- 4.4 * nc + 0.5
  if (is.null(height)) height <- 4.2 * nr + 0.4
  draw <- function() do.call(plot.basins4, c(list(b = b), dots[plot_args]))
  if (is.null(file)) draw() else {
    pdf(file, width = width, height = height); draw(); dev.off()
    if (png) {
      png(sub("\\.pdf$", ".png", file), width = 130 * width,
          height = 130 * height, res = 130)
      draw(); dev.off()
    }
  }
  invisible(b)
}

## ---------------------------------------------------------------------
## 4. Batch mode: produce the figures for a list of systems
## ---------------------------------------------------------------------
##  systems  : a list; each element describes ONE figure and is a list with
##               V            vectorised map (m x 4) -> (m x 4)   [required]
##               slice_values values at which the sliced coordinate is fixed
##               slice_coord  which coordinate is sliced (default 4)
##               file         output PDF name                       [required]
##             plus any further argument of basins_figure() /
##             basins_simplex4() / plot.basins4() (n_pix, png, cols, tol,
##             shade_strength, legend_xy, cex_*, ...) to override defaults
##  out_dir  : directory for the figures (created if needed)
##  log_file : text file collecting attractors and basin fractions
##  ...      : defaults for every figure (e.g. n_pix = 400, png = TRUE),
##             overridden by the per-system settings
basins_batch <- function(systems, out_dir = ".", log_file = "basins_log.txt", ...) {
  defaults <- list(...)
  if (!dir.exists(out_dir)) dir.create(out_dir, recursive = TRUE)
  if (!is.null(log_file)) {
    log_file <- file.path(out_dir, log_file)
    cat(sprintf("basins batch run, %s\n", format(Sys.time())), file = log_file)
  }
  for (i in seq_along(systems)) {
    s <- systems[[i]]
    nm <- if (!is.null(names(systems)) && nzchar(names(systems)[i])) names(systems)[i] else paste("system", i)
    if (is.null(s$V) || is.null(s$file))
      stop("entry '", nm, "' needs at least V and file")
    args <- modifyList(defaults, s)             # per-system settings win
    args$file <- file.path(out_dir, s$file)
    if (is.null(args$slice_values)) args$slice_values <- c(0, 0.2, 0.3, 0.4)
    cat(sprintf("\n=== %s  ->  %s\n", nm, args$file))
    t0 <- Sys.time()
    b <- do.call(basins_figure, args)
    dt <- as.numeric(difftime(Sys.time(), t0, units = "secs"))
    fr <- t(sapply(b$slices, function(sl) sl$fraction))
    rownames(fr) <- paste0("x", b$slice_coord, "=", b$slice_values)
    colnames(fr) <- c("not.conv", paste0("A", seq_len(nrow(b$attractors))))
    out <- c(sprintf("\n=== %s  (%s, %.1f s)", nm, args$file, dt),
             "attractors:",
             capture.output(print(cbind(id = paste0("A", seq_len(nrow(b$attractors))),
                                        round(b$attractors, 4)), quote = FALSE)),
             "fraction of each slice in each basin:",
             capture.output(print(round(fr, 3))))
    cat(out, sep = "\n")
    if (!is.null(log_file)) cat(out, file = log_file, sep = "\n", append = TRUE)
  }
  invisible(NULL)
}

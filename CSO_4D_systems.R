## =====================================================================
##  Systems file for batch production of basin-of-attraction figures.
##
##  HOW TO RUN (from the shell, in the directory containing basins.R):
##
##      Rscript CSO_4D_run_batch.R CSO_4D_systems.R [out_dir] [n_pix]
##
##      out_dir : directory for the figures (default ".", created if needed)
##      n_pix   : pixel width of every triangle (default 400); run time grows
##                with n_pix^2, so test with ~150 and produce with 400-600
##
##  or from an R session:
##
##      source("CSO_4D_basins.R"); source("CSO_4D_systems.R")
##      basins_batch(systems, out_dir = "figs", n_pix = 400, png = TRUE)
##
##  For every entry of `systems` a PDF (and a PNG) is written, and the file
##  out_dir/basins_log.txt collects the attractors found, the fraction of
##  each slice belonging to each basin, and the run time.
##
##  FORMAT OF THIS FILE
##
##  1. Define each map as an R function that takes an (m x 4) matrix X,
##     one point of the simplex per row, and returns an (m x 4) matrix of
##     images (use the columns X[,1], ..., X[,4] and cbind()).  The map must
##     keep the simplex invariant (rows of the result sum to 1).
##
##  2. Define a list called `systems`.  Each element describes ONE figure
##     and is itself a list with the fields
##
##        V            the map                                      [required]
##        file         name of the output PDF                       [required]
##        slice_values values at which the sliced coordinate is fixed, one
##                     panel each; 4 values -> 2x2 grid, 6 -> 2x3, 9 -> 3x3
##                     (values in [0,1); default c(0, 0.2, 0.3, 0.4))
##        slice_coord  which coordinate is sliced, 1..4 (default 4)
##
##     and optionally any further argument of basins_figure(),
##     basins_simplex4() or plot.basins4() to override the defaults for
##     that figure, e.g.
##
##        n_pix, max_iter, tol, cluster_tol        (computation)
##        png, width, height                        (output)
##        cols, col_nonconv, shade_strength,        (appearance)
##        legend_xy, cex_main, cex_lab, cex_legend
##
##     The same map may appear in several entries (different coordinates
##     or slice sets); this is how a non-symmetric system is covered.
##     Element names are only used in the log.
## =====================================================================

## --- Tree derived distance CSO examples 1,2 ---------------------------
V_CSO_Tree_1_2 <- function(X) {
  x1 <- X[, 1]; x2 <- X[, 2]; x3 <- X[, 3]; x4 <- X[, 4]
  cbind(x1^3 + 3*x1^2*(1-x1) + 4*x1*x2*x3 + 4*x1*x2*x4 + 4*x1*x3*x4,
        x2^3 + 3*x2^2*(1-x2) + 2*x1*x2*x3 + 2*x1*x2*x4 + 4*x2*x3*x4,
        x3^3 + 3*x3^2*(1-x3) + 2*x1*x3*x4 + 2*x2*x3*x4,
        x4^3 + 3*x4^2*(1-x4) )
}

